async function verifyFacultyImageUpload() {
  // Minimal valid 1x1 JPEG.
  const jpegBytes = Uint8Array.from([
    0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10,
    0x4a, 0x46, 0x49, 0x46, 0x00, 0x01,
    0x01, 0x00, 0x00, 0x01, 0x00, 0x01,
    0x00, 0x00,
    0xff, 0xdb, 0x00, 0x43, 0x00,
    0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08,
    0x07, 0x07, 0x07, 0x09, 0x09, 0x08, 0x0a,
    0x0c, 0x14, 0x0d, 0x0c, 0x0b, 0x0b, 0x0c,
    0x19, 0x12, 0x13, 0x0f, 0x14, 0x1d, 0x1a,
    0x1f, 0x1e, 0x1d, 0x1e, 0x1e, 0x1e, 0x1e,
    0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e,
    0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e,
    0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e,
    0x1e, 0x1e, 0x1e, 0x1e, 0x1e, 0x1e,
    0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01,
    0x00, 0x01, 0x01, 0x01, 0x11, 0x00,
    0xff, 0xc4, 0x00, 0x14, 0x00, 0x01, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x08,
    0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00,
    0x00, 0x3f, 0x00, 0xd2, 0xcf, 0x20,
    0xff, 0xd9,
  ]);

  const formData = new FormData();

  formData.append(
    "name",
    "API Upload Test Faculty"
  );

  formData.append(
    "designation",
    "Lecturer"
  );

  formData.append(
    "qualification",
    "M.Sc."
  );

  formData.append(
    "image",
    new Blob([jpegBytes], {
      type: "image/jpeg",
    }),
    "test-image.jpg"
  );

  const result = await request("/faculty/", {
    method: "POST",
    body: formData,
  });

  assert(
    result.response.status === 201,
    `Faculty image upload failed: HTTP ${result.response.status} ${JSON.stringify(
      result.data
    )}`
  );

  assert(
    typeof result.data?.image_url === "string" &&
      result.data.image_url.length > 0,
    "Faculty upload response does not contain image_url."
  );

  const id = result.data.id;

  pass("Faculty image upload");
  pass("Faculty image_url response");

  const deleteResult = await request(`/faculty/${id}/`, {
    method: "DELETE",
  });

  assert(
    deleteResult.response.status === 204,
    `Faculty upload cleanup delete failed: HTTP ${deleteResult.response.status}`
  );

  pass("Faculty uploaded file cleanup");
}